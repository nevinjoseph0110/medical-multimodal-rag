EXAMPLE_PROMPTS = [
    "What could be causing my headache?",
    "I have a red rash on my arm",
    "I've had a fever and cough for 3 days",
    "I have stomach pain after eating",
]


def render_welcome():
    st.markdown(
        """
        <div class="welcome-wrap">
            <p class="welcome-title">How can I help you today?</p>
            <p class="welcome-subtitle">
                Describe your symptoms in your own words. You can also
                upload a medical image for multimodal analysis.
            </p>
        </div>
        """,
        unsafe_allow_html=True,
    )

    st.markdown('<p class="example-label">Try an example</p>', unsafe_allow_html=True)
    cols = st.columns(2)
    for i, prompt in enumerate(EXAMPLE_PROMPTS):
        with cols[i % 2]:
            if st.button(prompt, key=f"example_{i}", use_container_width=True):
                submit_message(prompt)
                st.rerun()


def render_chat_message(message: dict):
    role = message["role"]
    timestamp = message.get("time", "")

    if role == "user":
        st.markdown(
            f"""
            <div class="chat-row user">
                <div>
                    <div class="bubble-user">{message["content"]}</div>
                    <div class="bubble-meta" style="text-align:right;">{timestamp}</div>
                </div>
            </div>
            """,
            unsafe_allow_html=True,
        )
        if message.get("image"):
            render_uploaded_image(message["image"], inline=True)
    else:
        render_response_card(message["content"], timestamp)


def urgency_badge_html(urgency: str) -> str:
    if urgency == EMERGENCY:
        css_class = "urgency-emergency"
        label = "⚠ EMERGENCY"
    elif urgency == CONSULT_DOCTOR:
        css_class = "urgency-consult"
        label = "CONSULT DOCTOR"
    else:
        css_class = "urgency-self-care"
        label = "SELF-CARE"

    return f'<span class="urgency-badge {css_class}">{label}</span>'


def render_response_card(response: dict, timestamp: str = ""):
    urgency = response.get("urgency", SELF_CARE)
    conditions = response.get("possible_conditions", [])
    condition_text = conditions[0] if conditions else "General guidance"

    warning_signs = response.get("warning_signs", [])
    warning_items = "".join(f"<li>{w}</li>" for w in warning_signs)

    emergency_block = ""
    if urgency == EMERGENCY:
        emergency_block = f"""
        <div class="emergency-box">
            🚨 {response.get('recommended_action', 'Seek emergency medical attention immediately.')}
        </div>
        """

    image_note_block = ""
    if response.get("image_note"):
        image_note_block = f"""
        <div class="response-section">
            <div class="response-label">Image note</div>
            <div class="response-value">{response['image_note']}</div>
        </div>
        """

    card_html = f"""
    <div class="chat-row assistant">
        <div class="response-card">
            <div class="response-section">
                <div class="response-label">Possible condition</div>
                <div class="condition-name">{condition_text}</div>
            </div>

            <div class="response-section">
                <div class="response-label">What this may mean</div>
                <div class="response-value">{response.get('what_it_may_mean', response.get('response', ''))}</div>
            </div>

            <div class="response-section">
                <div class="response-label">Urgency</div>
                {urgency_badge_html(urgency)}
                {emergency_block}
            </div>

            <div class="response-section">
                <div class="response-label">Recommended action</div>
                <div class="response-value">{response.get('recommended_action', '')}</div>
            </div>

            <div class="response-section">
                <div class="response-label">Watch for</div>
                <div class="response-value"><ul>{warning_items}</ul></div>
            </div>

            {image_note_block}

            <div class="disclaimer-box">
                This is preliminary AI-generated guidance and does not
                constitute a medical diagnosis. If you are concerned about
                your symptoms, consult a qualified healthcare professional.
            </div>
        </div>
    </div>
    """
    st.markdown(card_html, unsafe_allow_html=True)


def render_uploaded_image(image_file, inline: bool = False):
    st.markdown('<div class="image-card">Medical image</div>', unsafe_allow_html=True)
    st.image(image_file, use_container_width=True)
    st.markdown('<div class="image-received">✓ Image received</div>', unsafe_allow_html=True)
    if not inline:
        st.caption(
            "Multimodal image analysis will be connected during backend "
            "integration."
        )


def clear_chat():
    st.session_state.messages = []
    st.session_state.pending_prompt = None


def submit_message(text: str, image=None):
    """Add a user message and the mock assistant response to history."""
    now = datetime.now().strftime("%I:%M %p")

    st.session_state.messages.append(
        {"role": "user", "content": text, "time": now, "image": image}
    )

    response = generate_response(text, image)

    st.session_state.messages.append(
        {"role": "assistant", "content": response, "time": now}
    )


# ============================================================
# MAIN APP
# ============================================================

def main():
    load_styles()

    if "messages" not in st.session_state:
        st.session_state.messages = []

    render_header()
    render_sidebar()

    if len(st.session_state.messages) == 0:
        render_welcome()
    else:
        for message in st.session_state.messages:
            render_chat_message(message)

    st.markdown("<br>", unsafe_allow_html=True)

    with st.form(key="input_form", clear_on_submit=True):
        symptom_text = st.text_area(
            "Describe your symptoms here...",
            placeholder="Describe your symptoms here...",
            label_visibility="collapsed",
            height=90,
        )

        uploaded_image = st.file_uploader(
            "Upload medical image (optional)",
            type=["png", "jpg", "jpeg"],
            help="Optional. Supported formats: PNG, JPG, JPEG.",
        )

        submitted = st.form_submit_button("Send", use_container_width=True)

    if submitted and (symptom_text.strip() or uploaded_image is not None):
        submit_message(symptom_text.strip(), uploaded_image)
        st.rerun()


if __name__ == "__main__":
    main()
