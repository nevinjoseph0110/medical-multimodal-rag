def generate_response(symptoms: str, image=None) -> dict:
    """
    Mock backend response generator.

    THIS IS THE FUTURE INTEGRATION POINT.

    Later, this function's body will be replaced with a call into the
    real pipeline: preprocessing -> multimodal encoder -> RAG retrieval
    -> grounded response generation -> safety/triage filter. The return
    shape below is designed to match what that pipeline is expected to
    produce, so the frontend will not need to change.

    For now, it uses simple keyword-based mock logic purely for
    demonstration purposes. This is NOT a real diagnostic algorithm.
    """
    text = (symptoms or "").lower()

    emergency_terms = [
        "chest pain", "difficulty breathing", "can't breathe",
        "cannot breathe", "shortness of breath", "severe bleeding",
        "heavy bleeding", "loss of consciousness", "unconscious",
        "fainted", "stroke", "slurred speech", "seizure",
        "severe allergic reaction", "anaphylaxis", "not breathing",
        "blue lips", "crushing pain",
    ]

    fever_cough_terms = ["fever", "cough"]

    headache_terms = ["headache", "mild headache", "stress", "dehydration", "tired"]

    if any(term in text for term in emergency_terms):
        response = {
            "response": (
                "The symptoms you've described may indicate a serious medical "
                "emergency."
            ),
            "possible_conditions": ["Potential medical emergency"],
            "urgency": EMERGENCY,
            "what_it_may_mean": (
                "Symptoms like these can sometimes be associated with serious "
                "conditions that need immediate attention. This assistant "
                "cannot confirm what is happening, but the combination of "
                "symptoms you described should not be ignored."
            ),
            "recommended_action": (
                "Seek emergency medical attention immediately. Call your "
                "local emergency number or go to the nearest emergency room "
                "right away. Do not wait to see if symptoms improve."
            ),
            "warning_signs": [
                "Symptoms getting worse or spreading",
                "New or worsening pain",
                "Any loss of consciousness",
            ],
            "sources": [],
        }

    elif all(term in text for term in fever_cough_terms):
        response = {
            "response": (
                "Your combination of symptoms may be consistent with a "
                "respiratory infection."
            ),
            "possible_conditions": ["Respiratory infection"],
            "urgency": CONSULT_DOCTOR,
            "what_it_may_mean": (
                "Fever together with a cough can be caused by a range of "
                "respiratory infections, from mild viral illnesses to "
                "conditions that need medical treatment. It is difficult to "
                "know which one without an examination."
            ),
            "recommended_action": (
                "Consider speaking with a healthcare professional, "
                "especially if your fever is high, lasts more than a couple "
                "of days, or is accompanied by other symptoms. Rest and "
                "stay hydrated in the meantime."
            ),
            "warning_signs": [
                "Difficulty breathing or shortness of breath",
                "Fever above 39.4°C (103°F) or lasting more than 3 days",
                "Chest pain or confusion",
            ],
            "sources": [],
        }

    elif any(term in text for term in headache_terms) and "chest pain" not in text:
        response = {
            "response": (
                "Your symptoms may be consistent with a tension-type "
                "headache."
            ),
            "possible_conditions": ["Tension-type headache"],
            "urgency": SELF_CARE,
            "what_it_may_mean": (
                "Tension-type headaches are common and are often linked to "
                "stress, dehydration, poor sleep, or eye strain. They "
                "usually feel like a dull, steady pressure rather than a "
                "sharp pain."
            ),
            "recommended_action": (
                "Consider resting in a quiet space, drinking water, and "
                "monitoring how you feel over the next few hours. Over-the-"
                "counter pain relief may help, but please follow the "
                "label instructions or ask a pharmacist."
            ),
            "warning_signs": [
                "Sudden, severe headache unlike any before",
                "Headache with fever, stiff neck, or confusion",
                "Headache following a head injury",
            ],
            "sources": [],
        }

    else:
        response = {
            "response": (
                "I'd need a bit more information to provide useful "
                "preliminary guidance."
            ),
            "possible_conditions": [],
            "urgency": CONSULT_DOCTOR,
            "what_it_may_mean": (
                "Your description doesn't yet give me enough detail to "
                "narrow things down, even at a preliminary level."
            ),
            "recommended_action": (
                "Please share when the symptoms started, how severe they "
                "are, and any other symptoms you've noticed. This will "
                "help provide more relevant guidance."
            ),
            "warning_signs": [
                "Symptoms that suddenly worsen",
                "New symptoms appearing alongside the original ones",
            ],
            "sources": [],
        }

    if image is not None:
        response["image_note"] = (
            "Image uploaded successfully. Multimodal image analysis will "
            "be connected during backend integration."
        )

    # Run the mock response through the (placeholder) safety pipeline.
    response = run_safety_pipeline(symptoms, response)

    return response


